"""Step 5 - Monte Carlo evaluation over nominal, varied and disturbed conditions (Part E).

Scenarios (tb3nav/scenarios.py), each over several seeds (the seed changes the sensor noise
and, except for `nominal`, the obstacle layout, the start pose and the disturbance):

  nominal          fixed layout, sensor noise only
  random_layout    obstacles moved up to ±25 cm, start pose ±0.2 m / ±0.6 rad
  push             + a 25 N, 0.3 s shove in a random direction mid-mission
  slip             + slippery floor everywhere (mu 0.25; odometry calibrated at mu 1.0)
  encoder_bias     + uncalibrated wheel-radius error (left +4 %, right -1 %)
  camera_degraded  + pixel noise x3 and 40 % of camera frames dropped
  combined         push + encoder bias + degraded camera + noisy LiDAR

Run:   python scripts/05_monte_carlo.py            (runs missing trials, then reports)
       python scripts/05_monte_carlo.py --report   (report from cached results only)
Output: results/monte_carlo.md, results/monte_carlo.json, results/figures/mc_*.png
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from tb3nav.batch import run_jobs

BATCH = ROOT / "results" / "batch"
FIG = ROOT / "results" / "figures"
PLAN = {"nominal": 5, "random_layout": 8, "push": 6, "slip": 6, "encoder_bias": 6,
        "camera_degraded": 6, "combined": 6}


def job(scenario, seed, opts=None, cfg=None, tag=""):
    name = f"{scenario}_s{seed}" + (f"_{tag}" if tag else "")
    return {"name": name, "scenario": scenario, "seed": seed, "opts": opts or {},
            "cfg": cfg or {}, "out_dir": str(BATCH)}


def mc_jobs():
    return [job(sc, s) for sc, n in PLAN.items() for s in range(n)]


def agg(rows, key, fn=np.nanmean):
    v = np.array([r[key] for r in rows], float)
    return float(fn(v)) if len(v) else np.nan


def report(results):
    by = {}
    for r in results:
        if "error" in r or r.get("opts") or r.get("cfg"):
            continue
        by.setdefault(r["scenario"], []).append(r)
    lines = ["| Scenario | Trials | Docked (success) | Dock pos. err. [cm] mean / max | "
             "Dock yaw err. [deg] mean | Est. RMSE pos [cm] | Est. RMSE yaw [deg] | Mean NEES (3 ideal) | "
             "NEES in 95% band | Track RMSE lat. [cm] | Collisions | Re-localisations | Time [s] |",
             "|" + "---|" * 13]
    summary = {}
    for sc in PLAN:
        rows = by.get(sc, [])
        if not rows:
            continue
        succ = np.mean([r["success"] for r in rows])
        s = {"n": len(rows), "success_rate": float(succ),
             "dock_pos_mean_cm": 100 * agg(rows, "dock_pos_err_m"),
             "dock_pos_max_cm": 100 * agg(rows, "dock_pos_err_m", np.nanmax),
             "dock_yaw_mean_deg": agg([{"v": abs(r["dock_yaw_err_deg"])} for r in rows], "v"),
             "est_rmse_cm": 100 * agg(rows, "est_rmse_pos_m"),
             "est_rmse_yaw_deg": agg(rows, "est_rmse_yaw_deg"),
             "mean_nees": agg(rows, "mean_nees"), "nees_in_95": agg(rows, "nees_in_95"),
             "track_lat_cm": 100 * agg(rows, "track_rmse_lat_m"),
             "collisions": int(sum(r["collisions"] for r in rows)),
             "relocalise": int(sum(r.get("n_relocalise", 0) for r in rows)),
             "time_s": agg(rows, "mission_time_s"),
             "push_recovery_s": agg(rows, "push_recovery_s"),
             "push_peak_err_cm": 100 * agg(rows, "push_peak_err_m")}
        summary[sc] = s
        lines.append(f"| {sc} | {s['n']} | {100*succ:.0f} % | {s['dock_pos_mean_cm']:.2f} / "
                     f"{s['dock_pos_max_cm']:.2f} | {s['dock_yaw_mean_deg']:.2f} | {s['est_rmse_cm']:.2f} | "
                     f"{s['est_rmse_yaw_deg']:.2f} | {s['mean_nees']:.2f} | {100*s['nees_in_95']:.0f} % | "
                     f"{s['track_lat_cm']:.2f} | {s['collisions']} | {s['relocalise']} | {s['time_s']:.0f} |")
    table = "\n".join(lines)
    fails = [r for sc in PLAN for r in by.get(sc, []) if not r["success"]]
    fail_lines = [f"- `{r['name']}`: reached_done={r['reached_done']}, dock error "
                  f"{100*r['dock_pos_err_m']:.1f} cm / {r['dock_yaw_err_deg']:.1f} deg, collisions "
                  f"{r['collisions']}, est. RMSE {100*r['est_rmse_pos_m']:.1f} cm" for r in fails]
    md = ["# Monte Carlo results", "", "Success = reached the dock pose with position error < 3 cm "
          "and heading error < 5 deg, no collision. Generated by `scripts/05_monte_carlo.py`.", "",
          table, "", "## Failed trials", ""] + (fail_lines or ["None."])
    push = by.get("push", [])
    if push:
        md += ["", "## Push recovery", "",
               "| Trial | Push displacement [cm] | Peak estimate error [cm] | Recovery time [s] |",
               "|---|---|---|---|"]
        for r in push:
            md.append(f"| {r['name']} | {100*r['push_true_disp_m']:.1f} | {100*r['push_peak_err_m']:.1f} | "
                      f"{r['push_recovery_s']:.2f} |")
    (ROOT / "results" / "monte_carlo.md").write_text("\n".join(md) + "\n")
    (ROOT / "results" / "monte_carlo.json").write_text(json.dumps(summary, indent=2))
    print(table)
    plot_mc(by)
    return summary


def plot_mc(by):
    FIG.mkdir(parents=True, exist_ok=True)
    scs = [s for s in PLAN if s in by]
    fig, ax = plt.subplots(1, 4, figsize=(18, 4.2))
    for i, sc in enumerate(scs):
        rows = by[sc]
        for k, (key, scale) in enumerate((("dock_pos_err_m", 100), ("est_rmse_pos_m", 100),
                                          ("track_rmse_lat_m", 100), ("mean_nees", 1))):
            v = np.array([r[key] for r in rows]) * scale
            ok = np.array([r["success"] for r in rows])
            x = i + np.random.default_rng(i).uniform(-0.15, 0.15, len(v))
            ax[k].scatter(x[ok], v[ok], s=18, color="tab:blue")
            ax[k].scatter(x[~ok], v[~ok], s=30, color="tab:red", marker="x")
            ax[k].plot([i - 0.3, i + 0.3], [np.median(v)] * 2, "k-", lw=1.5)
    titles = ["Final docking position error [cm]", "Estimation RMSE (position) [cm]",
              "True cross-track tracking RMSE [cm]", "Mean NEES (consistent = 3)"]
    for k, a in enumerate(ax):
        a.set_xticks(range(len(scs))); a.set_xticklabels(scs, rotation=35, ha="right", fontsize=8)
        a.set_title(titles[k], fontsize=10); a.grid(alpha=0.3, axis="y")
    ax[0].axhline(3, color="r", ls="--", lw=0.8); ax[3].axhline(3, color="g", ls="--", lw=0.8)
    ax[0].set_yscale("log"); ax[3].set_yscale("log")
    fig.suptitle("Monte Carlo: blue = docked, red x = failed, black bar = median")
    fig.tight_layout(); fig.savefig(FIG / "mc_summary.png", dpi=120); plt.close(fig)

    # NEES / error-vs-sigma aggregated over all successful trials of each scenario
    fig, ax = plt.subplots(1, 2, figsize=(13, 4))
    for sc in scs:
        all_e, all_s = [], []
        for r in by[sc]:
            f = BATCH / f"{r['name']}.npz"
            if not f.exists():
                continue
            z = np.load(f)
            m = ~np.all(z["est"] == 0, axis=1)
            e = np.hypot(*(z["est"][m, :2] - z["true"][m, :2]).T)
            sd = np.sqrt(np.trace(z["P"][m, :2, :2], axis1=1, axis2=2))
            all_e.append(e); all_s.append(sd)
        if all_e:
            e, sd = np.concatenate(all_e), np.concatenate(all_s)
            ax[0].hist(e / np.maximum(sd, 1e-9), bins=np.linspace(0, 4, 41), histtype="step",
                       density=True, label=sc)
            ax[1].scatter(100 * sd[::25], 100 * e[::25], s=3, alpha=0.4, label=sc)
    from scipy.stats import chi
    xx = np.linspace(0, 4, 100)
    ax[0].plot(xx, chi.pdf(xx, 2), "k--", lw=1.5, label="ideal (chi, 2 dof)")
    ax[0].set_xlabel("position error / predicted std"); ax[0].legend(fontsize=7)
    ax[0].set_title("Estimator consistency (position), all trials")
    lim = ax[1].get_xlim()[1]
    ax[1].plot([0, lim], [0, lim], "k--", lw=1); ax[1].plot([0, lim], [0, 3 * lim], "r:", lw=1)
    ax[1].set_xlabel("EKF predicted position std [cm]"); ax[1].set_ylabel("actual error [cm]")
    ax[1].set_title("Actual error vs predicted std (dashed: 1x, dotted: 3x)")
    fig.tight_layout(); fig.savefig(FIG / "mc_consistency.png", dpi=120); plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true", help="only build the report from cache")
    ap.add_argument("--workers", type=int, default=None)
    a = ap.parse_args()
    jobs = mc_jobs()
    if a.report:
        res = [json.loads((BATCH / f"{j['name']}.json").read_text()) for j in jobs
               if (BATCH / f"{j['name']}.json").exists()]
    else:
        res = run_jobs(jobs, workers=a.workers)
    report(res)


if __name__ == "__main__":
    main()
