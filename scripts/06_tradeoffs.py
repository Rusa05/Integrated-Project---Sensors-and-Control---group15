"""Step 6 - Quantified trade-offs and ablations (Parts C, D and the Distinction/HD analysis).

  A. EKF process-noise scale q   (push scenario):   consistency (NEES) vs responsiveness
                                                     (push recovery time, re-localisations)
  B. EKF measurement-noise scale (random layouts):  trusting the camera vs consistency
  C. LQR control-weight scale    (random layouts):  tracking error vs control effort
  D. Measurement model ablation  (random layouts):  range+bearing+yaw (default) vs
                                                     range+bearing only vs odometry only

Every point is the mean over 3-4 seeded missions. Runs with default settings are shared with
scripts/05_monte_carlo.py through the cache in results/batch/.

Run:   python scripts/06_tradeoffs.py            python scripts/06_tradeoffs.py --report
Output: results/tradeoffs.md, results/figures/tradeoff_*.png
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from tb3nav.batch import run_jobs

BATCH = ROOT / "results" / "batch"
FIG = ROOT / "results" / "figures"

Q_SCALES = [0.1, 0.3, 1.0, 3.0, 10.0]
R_SCALES = [0.1, 0.3, 1.0, 3.0]
LQR_SCALES = [0.1, 0.3, 1.0, 3.0, 10.0]
SEEDS = [0, 1, 2]


def job(scenario, seed, opts=None, tag=""):
    name = f"{scenario}_s{seed}" + (f"_{tag}" if tag else "")
    return {"name": name, "scenario": scenario, "seed": seed, "opts": opts or {},
            "out_dir": str(BATCH)}


def sweep_jobs():
    J = {"A": [], "B": [], "C": [], "D": []}
    for q in Q_SCALES:
        for s in SEEDS:
            J["A"].append((q, job("push", s, {"ekf_q_scale": q} if q != 1 else None,
                                  f"q{q}" if q != 1 else "")))
    for r in R_SCALES:
        for s in SEEDS:
            J["B"].append((r, job("random_layout", s, {"ekf_r_scale": r} if r != 1 else None,
                                  f"r{r}" if r != 1 else "")))
    for k in LQR_SCALES:
        for s in SEEDS:
            J["C"].append((k, job("random_layout", s, {"lqr_r_scale": k} if k != 1 else None,
                                  f"lqr{k}" if k != 1 else "")))
    for s in SEEDS + [3]:
        J["D"].append(("range+bearing+yaw", job("random_layout", s)))
        J["D"].append(("range+bearing", job("random_layout", s, {"use_yaw": False}, "noyaw")))
        J["D"].append(("odometry only", job("random_layout", s, {"odometry_only": True}, "odo")))
    return J


def load(j):
    f = BATCH / f"{j['name']}.json"
    return json.loads(f.read_text()) if f.exists() else None


def group(pairs):
    out = {}
    for key, j in pairs:
        m = load(j)
        if m and "error" not in m:
            out.setdefault(key, []).append(m)
    return out


def mean(rows, k, scale=1.0):
    v = np.array([r[k] for r in rows], float) * scale
    return float(np.nanmean(v)), float(np.nanstd(v))


def report():
    J = sweep_jobs()
    md = ["# Trade-off studies", "", "Generated by `scripts/06_tradeoffs.py`; each row is the mean "
          "(± std) over the seeds listed. Default values are in bold.", ""]
    FIG.mkdir(parents=True, exist_ok=True)

    # ---------------- A: process noise
    A = group(J["A"])
    md += ["## A. EKF process-noise scale (push scenario, 3 seeds)", "",
           "| q scale | Est. RMSE [cm] | Mean NEES | NEES in 95 % band | Push peak err. [cm] | "
           "Push recovery [s] | Re-localisations | Docked |", "|---|---|---|---|---|---|---|---|"]
    xs = sorted(A)
    for q in xs:
        r = A[q]
        md.append(f"| {'**1.0**' if q == 1 else q} | {mean(r,'est_rmse_pos_m',100)[0]:.2f} ± {mean(r,'est_rmse_pos_m',100)[1]:.2f} | "
                  f"{mean(r,'mean_nees')[0]:.2f} | {100*mean(r,'nees_in_95')[0]:.0f} % | "
                  f"{mean(r,'push_peak_err_m',100)[0]:.1f} | {mean(r,'push_recovery_s')[0]:.2f} | "
                  f"{sum(x.get('n_relocalise',0) for x in r)} | {sum(x['success'] for x in r)}/{len(r)} |")
    if xs:
        fig, ax = plt.subplots(1, 3, figsize=(15, 4))
        nees = [mean(A[q], "mean_nees")[0] for q in xs]
        rmse = [mean(A[q], "est_rmse_pos_m", 100)[0] for q in xs]
        rec = [mean(A[q], "push_recovery_s")[0] for q in xs]
        ax[0].loglog(xs, nees, "o-"); ax[0].axhline(3, color="g", ls="--", label="consistent (3)")
        ax[0].set_xlabel("process-noise scale q"); ax[0].set_ylabel("mean NEES"); ax[0].legend()
        ax[0].set_title("Consistency")
        ax[1].semilogx(xs, rmse, "o-"); ax[1].set_xlabel("process-noise scale q")
        ax[1].set_ylabel("estimation RMSE [cm]"); ax[1].set_title("Accuracy")
        ax[2].semilogx(xs, rec, "o-", color="tab:red"); ax[2].set_xlabel("process-noise scale q")
        ax[2].set_ylabel("push recovery time [s]"); ax[2].set_title("Responsiveness to a push")
        for a in ax:
            a.axvline(1.0, color="k", lw=0.6, ls=":")
            a.grid(alpha=0.3)
        fig.suptitle("A. EKF process noise: consistency vs responsiveness (push scenario)")
        fig.tight_layout(); fig.savefig(FIG / "tradeoff_A_process_noise.png", dpi=120); plt.close(fig)

    # ---------------- B: measurement noise
    B = group(J["B"])
    md += ["", "## B. EKF measurement-noise scale (random layouts, 3 seeds)", "",
           "| R scale | Est. RMSE [cm] | Est. RMSE yaw [deg] | Mean NEES | Mean NIS/dof (1 ideal) | "
           "Gated updates | Dock err. [cm] | Docked |", "|---|---|---|---|---|---|---|---|"]
    for r_ in sorted(B):
        r = B[r_]
        md.append(f"| {'**1.0**' if r_ == 1 else r_} | {mean(r,'est_rmse_pos_m',100)[0]:.2f} | "
                  f"{mean(r,'est_rmse_yaw_deg')[0]:.2f} | {mean(r,'mean_nees')[0]:.2f} | "
                  f"{mean(r,'mean_nis_per_dof')[0]:.2f} | {mean(r,'n_gated')[0]:.1f} | "
                  f"{mean(r,'dock_pos_err_m',100)[0]:.2f} | {sum(x['success'] for x in r)}/{len(r)} |")

    # ---------------- C: LQR weights
    C = group(J["C"])
    md += ["", "## C. LQR control-weight scale R (random layouts, 3 seeds)", "",
           "| R_lqr scale | True cross-track RMSE [cm] | Max cross-track [cm] | Along-track RMSE [cm] | "
           "∫ω² dt | Σ|Δω| (chatter) | Mission time [s] | Docked |", "|---|---|---|---|---|---|---|---|"]
    ks = sorted(C)
    for k in ks:
        r = C[k]
        md.append(f"| {'**1.0**' if k == 1 else k} | {mean(r,'track_rmse_lat_m',100)[0]:.2f} | "
                  f"{mean(r,'track_max_lat_m',100)[0]:.2f} | {mean(r,'track_rmse_along_m',100)[0]:.2f} | "
                  f"{mean(r,'effort_w2')[0]:.2f} | {mean(r,'effort_dw')[0]:.1f} | "
                  f"{mean(r,'mission_time_s')[0]:.0f} | {sum(x['success'] for x in r)}/{len(r)} |")
    if ks:
        fig, ax = plt.subplots(1, 2, figsize=(11, 4))
        e = [mean(C[k], "track_rmse_lat_m", 100) for k in ks]
        u = [mean(C[k], "effort_dw") for k in ks]
        ax[0].errorbar([x[0] for x in u], [x[0] for x in e], xerr=[x[1] for x in u],
                       yerr=[x[1] for x in e], fmt="o-", capsize=3)
        for k, ee, uu in zip(ks, e, u):
            ax[0].annotate(f"R×{k}", (uu[0], ee[0]), textcoords="offset points", xytext=(5, 5), fontsize=8)
        ax[0].set_xlabel("control chatter Σ|Δω| [rad/s]"); ax[0].set_ylabel("cross-track RMSE [cm]")
        ax[0].set_title("Tracking error vs control effort (error flat: set by estimation, not control)"); ax[0].grid(alpha=0.3)
        ax[1].semilogx(ks, [mean(C[k], "effort_w2")[0] for k in ks], "o-")
        ax[1].set_xlabel("LQR R scale"); ax[1].set_ylabel("∫ω² dt"); ax[1].grid(alpha=0.3)
        ax[1].set_title("Yaw-rate effort")
        fig.tight_layout(); fig.savefig(FIG / "tradeoff_C_lqr.png", dpi=120); plt.close(fig)

    # ---------------- D: measurement model ablation
    D = group(J["D"])
    md += ["", "## D. Measurement-model ablation (random layouts, 4 seeds)", "",
           "| Configuration | Est. RMSE [cm] | Est. max err. [cm] | Est. RMSE yaw [deg] | Mean NEES | "
           "Dock err. [cm] | Docked | Collisions |", "|---|---|---|---|---|---|---|---|"]
    for k in ("range+bearing+yaw", "range+bearing", "odometry only"):
        r = D.get(k, [])
        if not r:
            continue
        md.append(f"| {'**' + k + '**' if k == 'range+bearing+yaw' else k} | "
                  f"{mean(r,'est_rmse_pos_m',100)[0]:.2f} | {mean(r,'est_max_pos_m',100)[0]:.2f} | "
                  f"{mean(r,'est_rmse_yaw_deg')[0]:.2f} | {mean(r,'mean_nees')[0]:.2f} | "
                  f"{mean(r,'dock_pos_err_m',100)[0]:.2f} | {sum(x['success'] for x in r)}/{len(r)} | "
                  f"{sum(x['collisions'] for x in r)} |")
    if D:
        fig, ax = plt.subplots(1, 2, figsize=(11, 4))
        keys = [k for k in ("range+bearing+yaw", "range+bearing", "odometry only") if k in D]
        for i, k in enumerate(keys):
            for kk, (key, a) in enumerate((("est_rmse_pos_m", ax[0]), ("dock_pos_err_m", ax[1]))):
                v = 100 * np.array([x[key] for x in D[k]])
                a.bar(i, np.mean(v), color=["tab:blue", "tab:orange", "tab:gray"][i], alpha=0.7)
                a.scatter([i] * len(v), v, color="k", s=10, zorder=3)
        for a, t in zip(ax, ("Estimation RMSE [cm]", "Final docking error [cm]")):
            a.set_xticks(range(len(keys))); a.set_xticklabels(keys); a.set_yscale("log")
            a.set_title(t); a.grid(alpha=0.3, axis="y")
        ax[1].axhline(3, color="r", ls="--", lw=0.8)
        fig.tight_layout(); fig.savefig(FIG / "tradeoff_D_ablation.png", dpi=120); plt.close(fig)

    (ROOT / "results" / "tradeoffs.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--workers", type=int, default=None)
    a = ap.parse_args()
    if not a.report:
        J = sweep_jobs()
        jobs, seen = [], set()
        for part in "DCBA":
            for _, j in J[part]:
                if j["name"] not in seen:
                    seen.add(j["name"]); jobs.append(j)
        run_jobs(jobs, workers=a.workers)
    report()


if __name__ == "__main__":
    main()
